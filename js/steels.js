/**
 * Получить характеристики стали по марке и толщине проката.
 * @param {string} grade — марка стали (ключ в STEELS, например "C345")
 * @param {number} thickness — толщина проката, мм
 * @returns {object|null} — объект характеристик или null, если марка или толщина не найдены
 */
function getSteelProps(grade, thickness) {
  const steel = STEELS[grade];
  if (!steel) return null;

  const t = parseFloat(thickness);
  if (isNaN(t) || t <= 0) return null;

  for (const range of steel.ranges) {
    if (t >= range.min && t <= range.max) {
      return {
        grade: steel.name,
        minThickness: range.min,
        maxThickness: range.max,
        Ryn: range.Ryn,
        Run: range.Run,
        Ry1: range.Ry[0],
        Ry2: range.Ry[1],
        Ru1: range.Ru[0],
        Ru2: range.Ru[1]
      };
    }
  }
  return null;
}

/**
 * Получить список всех марок сталей для отображения в интерфейсе.
 * @returns {Array<{key: string, name: string}>}
 */
function getSteelGrades() {
  return Object.keys(STEELS).map(key => ({
    key: key,
    name: STEELS[key].name
  }));
}

